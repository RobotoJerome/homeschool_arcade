<#
  Shred the Globe — data builder (optional maintenance tool)
  ----------------------------------------------------------
  Combines the hand-checked facts in tools\source\*.json with official
  population numbers and writes shred-the-globe\data\geo-data.js.

  You only need this if you want to refresh population numbers in a future year.
  Usage (from PowerShell, in the project folder):

      powershell -ExecutionPolicy Bypass -File tools\build-data.ps1 -Download

  -Download fetches the newest World Bank country populations and the US Census
  state estimates (set -CensusYear to the newest "Vintage" year Census has published).
#>
param(
  [string]$RawDir = (Join-Path $PSScriptRoot "raw"),
  [int]$CensusYear = 2025,
  [switch]$Download
)
$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot -Parent
$src  = Join-Path $PSScriptRoot "source"
$out  = Join-Path $root "shred-the-globe\data\geo-data.js"
New-Item -ItemType Directory -Force $RawDir | Out-Null

$wbFile     = Join-Path $RawDir "wb-pop.json"
$censusFile = Join-Path $RawDir "census-states.csv"
$wcFile     = Join-Path $RawDir "world-countries.json"

if ($Download) {
  Write-Host "Downloading World Bank population (latest available year)..."
  Invoke-WebRequest -UseBasicParsing -Uri "https://api.worldbank.org/v2/country/all/indicator/SP.POP.TOTL?format=json&mrnev=1&per_page=400" -OutFile $wbFile
  $cUrl = "https://www2.census.gov/programs-surveys/popest/datasets/2020-$CensusYear/state/totals/NST-EST$CensusYear-POPCHG2020-$CensusYear.csv"
  Write-Host "Downloading US Census state estimates: $cUrl"
  Invoke-WebRequest -UseBasicParsing -UserAgent "Mozilla/5.0" -Uri $cUrl -OutFile $censusFile
  if (-not (Test-Path $wcFile)) {
    Invoke-WebRequest -UseBasicParsing -Uri "https://cdn.jsdelivr.net/npm/world-countries@5.1.0/countries.json" -OutFile $wcFile
  }
}

function Read-Json($path) { Get-Content $path -Raw -Encoding UTF8 | ConvertFrom-Json }

# ---- World Bank populations, keyed by ISO3 ----
$wb = (Read-Json $wbFile)[1]
$pop = @{}
foreach ($r in $wb) { if ($r.value) { $pop[$r.countryiso3code] = @{ v = [int64]$r.value; y = [int]$r.date } } }

# ---- world-countries: ISO codes + regions ----
$wc = Read-Json $wcFile
$byA2 = @{}
foreach ($c in $wc) { $byA2[$c.cca2.ToLower()] = $c }

function Get-Continent($c) {
  switch ($c.region) {
    "Americas" { if ($c.subregion -eq "South America") { return "South America" } else { return "North America" } }
    default { return $c.region }
  }
}

# ---- Countries ----
$facts = Read-Json (Join-Path $src "country-facts.json")
$countries = New-Object System.Collections.ArrayList
foreach ($p in $facts.PSObject.Properties) {
  if ($p.Name.StartsWith("_")) { continue }
  $f = $p.Value; $a2 = $p.Name
  $c = $byA2[$a2]
  if (-not $c) { throw "No ISO record for $a2" }
  $pp = $pop[$c.cca3]
  if (-not $pp) { throw "No World Bank population for $a2 ($($c.cca3))" }
  $hide = @(); if ($f.hide) { $hide = @($f.hide) }
  [void]$countries.Add([ordered]@{
    id = $c.ccn3; iso = $a2; iso3 = $c.cca3; name = $f.name; capital = $f.capital
    cont = (Get-Continent $c); sub = $c.subregion
    pop = $pp.v; popYear = $pp.y
    fact = $f.fact; src = @($f.src); hide = $hide
  })
}

# ---- States ----
$census = Import-Csv $censusFile
$col = "POPESTIMATE$CensusYear"
$sfacts = Read-Json (Join-Path $src "state-facts.json")
$states = New-Object System.Collections.ArrayList
foreach ($p in $sfacts.PSObject.Properties) {
  if ($p.Name.StartsWith("_")) { continue }
  $f = $p.Value
  $row = $census | Where-Object { $_.NAME -eq $f.name -and $_.SUMLEV -eq "040" } | Select-Object -First 1
  if (-not $row) { throw "No Census row for $($f.name)" }
  [void]$states.Add([ordered]@{
    id = $f.fips; iso = $p.Name; name = $f.name; capital = $f.capital
    pop = [int64]$row.$col; popYear = $CensusYear
    fact = $f.fact; src = @($f.src); hide = @()
  })
}

$data = [ordered]@{
  built = (Get-Date -Format "yyyy-MM-dd")
  popWorld = [ordered]@{ label = "World Bank"; url = "https://data.worldbank.org/indicator/SP.POP.TOTL" }
  popUS = [ordered]@{ label = "U.S. Census Bureau (July 1 estimate)"; url = "https://www.census.gov/data/tables/time-series/demo/popest/2020s-state-total.html" }
  countries = $countries
  states = $states
}
$json = $data | ConvertTo-Json -Depth 6 -Compress
$js = "/* AUTO-GENERATED by tools/build-data.ps1 on $(Get-Date -Format 'yyyy-MM-dd'). Edit tools/source/*.json, not this file. */`nwindow.GEO = $json;`n"
[System.IO.File]::WriteAllText($out, $js, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $out  ($($countries.Count) countries, $($states.Count) states)"
